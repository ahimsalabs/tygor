package gen

import (
	"bytes"
	"context"
	"encoding/json/jsontext"
	json "encoding/json/v2"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"tygor.dev/internal/discover"
	"tygor.dev/internal/runner"
	"tygor.dev/tygorgen/provider"
	"tygor.dev/tygorgen/sink"
	"tygor.dev/tygorgen/typescript"
)

const (
	ownershipManifestName = ".tygor-generated.json"
	ownershipVersion      = 1
	generatedFileMarker   = "// Code generated by tygor. DO NOT EDIT."
)

type ownershipManifest struct {
	Version int      `json:"version"`
	Files   []string `json:"files"`
}

type Cmd struct {
	Out       string   `arg:"" help:"Output directory for generated files."`
	Export    string   `help:"Export function name (required if multiple exports exist)." short:"e"`
	Flavor    string   `help:"Output flavor (e.g., zod)." short:"f"`
	Discovery bool     `help:"Generate discovery.json." short:"d"`
	NoConfig  bool     `help:"Ignore config function."`
	Package   string   `help:"Package to scan (default: current directory)." short:"p" default:"."`
	Check     bool     `help:"Check if generated files are up-to-date (exit 1 if stale)." short:"c"`
	Types     []string `help:"Generate types without a tygor app (e.g., -t ErrorCode -t github.com/foo/bar.MyType)." short:"t" name:"type"`
}

func (c *Cmd) Run() error {
	// Standalone type generation mode
	if len(c.Types) > 0 {
		return c.runStandaloneTypes()
	}

	// Discover exports in the package
	result, err := discover.Find(c.Package)
	if err != nil {
		return fmt.Errorf("discover: %w", err)
	}

	// Select the export to use
	export, err := discover.SelectExport(result.Exports, c.Export)
	if err != nil {
		return err
	}

	// Validate flags for *tygorgen.Generator exports
	if export.Type == discover.ExportTypeGenerator {
		if c.Flavor != "" {
			return fmt.Errorf("--flavor not supported with *tygorgen.Generator export\n\nYour export returns *tygorgen.Generator - configuration is in code.\nAdd flavors in your generator function:\n\n    return tygorgen.FromApp(setupApp()).\n        WithFlavor(tygorgen.FlavorZod)")
		}
		if c.Discovery {
			return fmt.Errorf("--discovery not supported with *tygorgen.Generator export\n\nYour export returns *tygorgen.Generator - configuration is in code.\nEnable discovery in your generator function:\n\n    return tygorgen.FromApp(setupApp()).\n        WithDiscovery()")
		}
	}

	// Resolve output directory to absolute path
	outDir, err := filepath.Abs(c.Out)
	if err != nil {
		return fmt.Errorf("resolve output path: %w", err)
	}

	// Always stage generation so owned outputs can be reconciled as a set.
	genDir, err := os.MkdirTemp("", "tygor-gen-*")
	if err != nil {
		return fmt.Errorf("create temp dir: %w", err)
	}
	defer os.RemoveAll(genDir)

	// Build runner options
	opts := runner.Options{
		Export:          *export,
		OutDir:          genDir,
		Flavor:          c.Flavor,
		Discovery:       c.Discovery,
		NoConfig:        c.NoConfig,
		PkgDir:          result.Dir,
		PkgPath:         result.PackagePath,
		PackageName:     result.PackageName,
		CompiledGoFiles: result.CompiledGoFiles,
		ModulePath:      result.ModulePath,
		ModuleDir:       result.ModuleDir,
	}

	// Config ambiguity matters only when an app export will apply config.
	if export.Type == discover.ExportTypeApp && !c.NoConfig {
		config, err := discover.SelectConfig(result.ConfigFuncs)
		if err != nil {
			return err
		}
		if config != nil {
			opts.ConfigFunc = config.Name
		}
	}

	// Run the generator
	output, err := runner.Exec(opts)
	if err != nil {
		if len(output) > 0 {
			fmt.Fprint(os.Stderr, string(output))
		}
		return err
	}

	// Print any output (warnings, etc.)
	if len(output) > 0 {
		fmt.Print(string(output))
	}

	// In check mode, compare generated files with existing
	if c.Check {
		return c.compareFiles(genDir, outDir)
	}
	return c.reconcileFiles(genDir, outDir)
}

// compareFiles compares generated files in genDir with existing files in outDir.
// Returns an error if any files differ, are missing, or are stale.
func (c *Cmd) compareFiles(genDir, outDir string) error {
	expected, err := collectGeneratedFiles(genDir)
	if err != nil {
		return err
	}
	manifest, found, err := readOwnershipManifest(outDir)
	if err != nil {
		return err
	}
	if !found {
		return fmt.Errorf("generated ownership manifest %s is missing in %s; run 'tygor gen %s' once before using --check", ownershipManifestName, outDir, outDir)
	}

	owned := make(map[string]bool, len(manifest.Files))
	for _, path := range manifest.Files {
		owned[path] = true
	}
	expectedSet := make(map[string]bool, len(expected))
	var stale []string
	for _, name := range expected {
		expectedSet[name] = true
		genPath := filepath.Join(genDir, filepath.FromSlash(name))
		outPath := filepath.Join(outDir, filepath.FromSlash(name))

		genContent, err := os.ReadFile(genPath)
		if err != nil {
			return fmt.Errorf("read generated file %s: %w", name, err)
		}

		outContent, err := os.ReadFile(outPath)
		if err != nil {
			if os.IsNotExist(err) {
				stale = append(stale, name+" (missing)")
				continue
			}
			return fmt.Errorf("read existing file %s: %w", name, err)
		}

		if !bytes.Equal(genContent, outContent) {
			stale = append(stale, name+" (changed)")
		} else if !owned[name] {
			stale = append(stale, name+" (not recorded in ownership manifest)")
		}
	}
	for _, name := range manifest.Files {
		if !expectedSet[name] {
			stale = append(stale, name+" (obsolete)")
		}
	}

	if len(stale) > 0 {
		sort.Strings(stale)
		fmt.Fprintf(os.Stderr, "Generated files are out of date in %s:\n", outDir)
		for _, f := range stale {
			fmt.Fprintf(os.Stderr, "  %s\n", f)
		}
		fmt.Fprintf(os.Stderr, "\nRun 'tygor gen %s' to update.\n", outDir)
		return fmt.Errorf("generated files are stale")
	}

	return nil
}

func (c *Cmd) reconcileFiles(genDir, outDir string) error {
	expected, err := collectGeneratedFiles(genDir)
	if err != nil {
		return err
	}
	manifest, found, err := readOwnershipManifest(outDir)
	if err != nil {
		return err
	}
	if !found {
		manifest.Files, err = findLegacyGeneratedFiles(outDir)
		if err != nil {
			return err
		}
	}

	expectedSet := make(map[string]bool, len(expected))
	for _, path := range expected {
		expectedSet[path] = true
	}
	var obsolete []string
	for _, path := range manifest.Files {
		if !expectedSet[path] {
			obsolete = append(obsolete, path)
		}
	}
	if err := removeOwnedFiles(outDir, obsolete); err != nil {
		return err
	}

	output := sink.NewFilesystemSink(outDir)
	ctx := context.Background()
	for _, path := range expected {
		content, err := os.ReadFile(filepath.Join(genDir, filepath.FromSlash(path)))
		if err != nil {
			return fmt.Errorf("read staged file %s: %w", path, err)
		}
		if err := output.WriteFile(ctx, path, content); err != nil {
			return fmt.Errorf("publish generated file %s: %w", path, err)
		}
	}

	manifestData, err := json.Marshal(
		ownershipManifest{Version: ownershipVersion, Files: expected},
		json.Deterministic(true),
		jsontext.WithIndent("  "),
	)
	if err != nil {
		return fmt.Errorf("marshal ownership manifest: %w", err)
	}
	manifestData = append(manifestData, '\n')
	if err := output.WriteFile(ctx, ownershipManifestName, manifestData); err != nil {
		return fmt.Errorf("publish ownership manifest: %w", err)
	}
	return nil
}

func collectGeneratedFiles(root string) ([]string, error) {
	var files []string
	err := filepath.WalkDir(root, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		if rel == ownershipManifestName {
			return fmt.Errorf("generator output uses reserved path %s", ownershipManifestName)
		}
		if err := sink.ValidatePath(rel); err != nil {
			return fmt.Errorf("invalid generated path %q: %w", rel, err)
		}
		files = append(files, rel)
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("walk generated files: %w", err)
	}
	sort.Strings(files)
	return files, nil
}

func readOwnershipManifest(root string) (ownershipManifest, bool, error) {
	data, err := os.ReadFile(filepath.Join(root, ownershipManifestName))
	if os.IsNotExist(err) {
		return ownershipManifest{}, false, nil
	}
	if err != nil {
		return ownershipManifest{}, false, fmt.Errorf("read ownership manifest: %w", err)
	}
	var manifest ownershipManifest
	if err := json.Unmarshal(data, &manifest); err != nil {
		return ownershipManifest{}, false, fmt.Errorf("parse ownership manifest: %w", err)
	}
	if manifest.Version != ownershipVersion {
		return ownershipManifest{}, false, fmt.Errorf("unsupported ownership manifest version %d", manifest.Version)
	}
	seen := make(map[string]bool, len(manifest.Files))
	for _, path := range manifest.Files {
		if err := sink.ValidatePath(path); err != nil || path == ownershipManifestName {
			return ownershipManifest{}, false, fmt.Errorf("invalid owned path %q in ownership manifest", path)
		}
		if seen[path] {
			return ownershipManifest{}, false, fmt.Errorf("duplicate owned path %q in ownership manifest", path)
		}
		seen[path] = true
	}
	sort.Strings(manifest.Files)
	return manifest, true, nil
}

func findLegacyGeneratedFiles(root string) ([]string, error) {
	if _, err := os.Stat(root); os.IsNotExist(err) {
		return nil, nil
	} else if err != nil {
		return nil, fmt.Errorf("stat output directory: %w", err)
	}
	var files []string
	err := filepath.WalkDir(root, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			if path != root {
				if _, err := os.Stat(filepath.Join(path, ownershipManifestName)); err == nil {
					return filepath.SkipDir
				} else if !os.IsNotExist(err) {
					return err
				}
			}
			return nil
		}
		if entry.Type()&os.ModeSymlink != 0 || entry.Name() == ownershipManifestName {
			return nil
		}
		// Legacy ownership applies only to direct TypeScript source outputs.
		// Compiler derivatives may preserve the generated-file marker.
		if filepath.Ext(entry.Name()) != ".ts" || strings.HasSuffix(entry.Name(), ".d.ts") {
			return nil
		}
		content, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.HasPrefix(content, []byte(generatedFileMarker)) {
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		files = append(files, filepath.ToSlash(rel))
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("scan legacy generated files: %w", err)
	}
	sort.Strings(files)
	return files, nil
}

func removeOwnedFiles(root string, paths []string) error {
	parents := make(map[string]bool)
	for _, path := range paths {
		if err := validateOwnedDirectoryPath(root, filepath.Dir(filepath.FromSlash(path))); err != nil {
			return fmt.Errorf("inspect obsolete generated file %s: %w", path, err)
		}
		fullPath := filepath.Join(root, filepath.FromSlash(path))
		info, err := os.Lstat(fullPath)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return fmt.Errorf("inspect obsolete generated file %s: %w", path, err)
		}
		if info.IsDir() {
			return fmt.Errorf("obsolete generated path %s is now a directory", path)
		}
		if err := os.Remove(fullPath); err != nil {
			return fmt.Errorf("remove obsolete generated file %s: %w", path, err)
		}
		for parent := filepath.Dir(filepath.FromSlash(path)); parent != "."; parent = filepath.Dir(parent) {
			parents[parent] = true
		}
	}
	parentPaths := make([]string, 0, len(parents))
	for parent := range parents {
		parentPaths = append(parentPaths, parent)
	}
	sort.Slice(parentPaths, func(i, j int) bool { return len(parentPaths[i]) > len(parentPaths[j]) })
	for _, parent := range parentPaths {
		if err := validateOwnedDirectoryPath(root, parent); err != nil {
			return fmt.Errorf("inspect obsolete generated directory %s: %w", filepath.ToSlash(parent), err)
		}
		// Generated directories are not individually owned. Remove them only when
		// empty, and otherwise leave user-owned contents untouched.
		_ = os.Remove(filepath.Join(root, parent))
	}
	return nil
}

// validateOwnedDirectoryPath rejects symlinked and non-directory components
// below root without following them. The output root is the trust anchor. This
// check is not race-safe against concurrent replacement, so callers must own the
// output tree for the duration of reconciliation. Publication through
// FilesystemSink has separate trusted-tree limitations.
func validateOwnedDirectoryPath(root, relativeDir string) error {
	if relativeDir == "." || relativeDir == "" {
		return nil
	}

	current := root
	for _, component := range strings.Split(relativeDir, string(filepath.Separator)) {
		current = filepath.Join(current, component)
		info, err := os.Lstat(current)
		if os.IsNotExist(err) {
			return nil
		}
		if err != nil {
			return err
		}
		if info.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf("directory component %s is a symbolic link", filepath.ToSlash(component))
		}
		if !info.IsDir() {
			return fmt.Errorf("directory component %s is not a directory", filepath.ToSlash(component))
		}
	}
	return nil
}

// runStandaloneTypes generates TypeScript types directly from Go types
// without requiring a tygor app export.
func (c *Cmd) runStandaloneTypes() error {
	// Validate incompatible flags
	if c.Export != "" {
		return fmt.Errorf("--export cannot be used with --type")
	}
	if c.NoConfig {
		return fmt.Errorf("--no-config cannot be used with --type")
	}
	if err := validateFlavor(c.Flavor); err != nil {
		return err
	}

	// Parse type specifications into packages and root types
	packages, rootTypes, err := parseTypeSpecs(c.Types, c.Package)
	if err != nil {
		return err
	}

	// Resolve output directory
	outDir, err := filepath.Abs(c.Out)
	if err != nil {
		return fmt.Errorf("resolve output path: %w", err)
	}

	genDir, err := os.MkdirTemp("", "tygor-gen-*")
	if err != nil {
		return fmt.Errorf("create temp dir: %w", err)
	}
	defer os.RemoveAll(genDir)

	// Build schema using source provider
	ctx := context.Background()
	p := &provider.SourceProvider{}
	schema, err := p.BuildSchema(ctx, provider.SourceInputOptions{
		Packages:  packages,
		RootTypes: rootTypes,
	})
	if err != nil {
		return fmt.Errorf("build schema: %w", err)
	}

	// Validate schema
	if errs := schema.Validate(); len(errs) > 0 {
		return fmt.Errorf("schema validation: %w", errs[0])
	}

	// Configure TypeScript generator
	tsConfig := typescript.GeneratorConfig{
		FieldCase:       "preserve",
		TypeCase:        "preserve",
		SingleFile:      true, // Standalone types go in single file
		IndentStyle:     "space",
		IndentSize:      2,
		LineEnding:      "lf",
		TrailingNewline: true,
		EmitComments:    true,
		Custom: map[string]any{
			"EmitExport":        true,
			"EmitDeclare":       false,
			"UseInterface":      true,
			"UseReadonlyArrays": false,
			"EnumStyle":         "union",
			"OptionalType":      "default",
			"UnknownType":       "unknown",
			"EmitTypes":         true,
		},
	}

	// Add flavors if specified
	if c.Flavor != "" {
		tsConfig.Custom["Flavors"] = []string{c.Flavor}
	}

	// Create filesystem sink
	outputSink := sink.NewFilesystemSink(genDir)

	// Generate TypeScript
	gen := &typescript.TypeScriptGenerator{}
	result, err := gen.Generate(ctx, schema, typescript.GenerateOptions{
		Sink:   outputSink,
		Config: tsConfig,
	})
	if err != nil {
		return fmt.Errorf("generate: %w", err)
	}

	// Print warnings
	for _, w := range result.Warnings {
		fmt.Fprintf(os.Stderr, "warning: %s: %s\n", w.Code, w.Message)
	}

	// In check mode, compare files
	if c.Check {
		return c.compareFiles(genDir, outDir)
	}
	return c.reconcileFiles(genDir, outDir)
}

func validateFlavor(flavor string) error {
	if flavor == "" || flavor == "zod" || flavor == "zod-mini" {
		return nil
	}
	return fmt.Errorf("invalid flavor %q: expected zod or zod-mini", flavor)
}

// parseTypeSpecs parses type specifications like "ErrorCode" or "github.com/foo/bar.MyType"
// into packages to load and root types to extract.
func parseTypeSpecs(specs []string, defaultPkg string) ([]string, []provider.RootType, error) {
	seen := make(map[string]bool)
	var packages []string
	var rootTypes []provider.RootType

	for _, spec := range specs {
		var pkg, name string

		// Check if it's a fully qualified type (contains a dot after a slash)
		// e.g., "github.com/foo/bar.MyType" -> pkg="github.com/foo/bar", name="MyType"
		if lastDot := strings.LastIndex(spec, "."); lastDot > 0 {
			// Ensure there's a slash before the dot (it's a package path, not just "pkg.Type")
			if strings.Contains(spec[:lastDot], "/") {
				pkg = spec[:lastDot]
				name = spec[lastDot+1:]
			} else {
				// Could be "pkg.Type" which is ambiguous - treat as error
				return nil, nil, fmt.Errorf("ambiguous type %q: use fully qualified path (e.g., github.com/pkg.Type) or simple name with --package", spec)
			}
		} else {
			// Simple name like "ErrorCode" - use default package
			pkg = defaultPkg
			name = spec
		}

		if name == "" {
			return nil, nil, fmt.Errorf("invalid type specification: %q", spec)
		}

		// Add package if not seen
		if !seen[pkg] {
			seen[pkg] = true
			packages = append(packages, pkg)
		}

		rootTypes = append(rootTypes, provider.RootType{
			Package: pkg,
			Name:    name,
		})
	}

	return packages, rootTypes, nil
}
